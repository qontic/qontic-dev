function replaceTextNode(node) {
  if (node.nodeType !== Node.TEXT_NODE) return;
  let text = node.nodeValue;
  for (const [from, to] of replacements) text = text.replaceAll(from, to);
  node.nodeValue = text;
}

function updateElement(element) {
  if (!(element instanceof Element)) return;
  if (element.matches('label') && element.textContent.trim().startsWith('Position width')) {
    const text=[...element.childNodes].find((node)=>node.nodeType===Node.TEXT_NODE); if(text) text.nodeValue='σ';
    element.title='Initial X position width σx. It controls the system packet and detector-region boundaries.';
  }
  if (element.matches('label') && element.textContent.trim().startsWith('Pointer width')) {
    const text=[...element.childNodes].find((node)=>node.nodeType===Node.TEXT_NODE); if(text) text.nodeValue='σ';
    element.title='Weak-pointer Y position width σy. Larger values increase overlap between weak-measurement branches.';
  }
  element.childNodes.forEach(replaceTextNode);
  for (const attribute of ["title", "data-help", "aria-label"]) {
    if (!element.hasAttribute(attribute)) continue;
    let value = element.getAttribute(attribute);
    value = exactTextReplacements.get(value) ?? value;
    for (const [from, to] of replacements) value = value.replaceAll(from, to);
    element.setAttribute(attribute, value);
  }
}

